#!/usr/bin/env node
/*
 * Generates THIRD-PARTY-NOTICES.md by walking the *production* dependency tree
 * and reproducing each bundled package's license text.
 *
 * Offline: reads installed package.json + LICENSE files from node_modules only.
 * Walks both the backend (root) and the bundled admin web app (_admin) production
 * dependency trees, since both ship in the release artifacts. Run after
 * `npm install` in both trees so the tree reflects what actually ships.
 *
 *   npm install && npm install --prefix _admin
 *   node scripts/gen-third-party-notices.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const ADMIN = path.join(ROOT, '_admin');
const OUT = path.join(ROOT, 'THIRD-PARTY-NOTICES.md');
const LICENSE_FILES = [
  'LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'LICENCE.md',
  'license', 'license.md', 'COPYING', 'COPYING.md', 'NOTICE',
];

// Resolve a package directory using Node's node_modules lookup, starting from `fromDir`.
function resolvePackageDir(name, fromDir) {
  let dir = fromDir;
  while (true) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function normalizeLicense(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && pkg.license.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type || l).join(' OR ');
  if (pkg.licenses && pkg.licenses.type) return pkg.licenses.type;
  return 'UNKNOWN';
}

function readLicenseText(dir) {
  for (const f of LICENSE_FILES) {
    const p = path.join(dir, f);
    if (fs.existsSync(p)) {
      try {
        return fs.readFileSync(p, 'utf8').trim();
      } catch (_) { /* ignore */ }
    }
  }
  return null;
}

function authorOf(pkg) {
  if (typeof pkg.author === 'string') return pkg.author;
  if (pkg.author && pkg.author.name) return pkg.author.name;
  return null;
}

// Seed the traversal from each shipped tree's direct production dependencies.
function seedQueue(fromDir) {
  const pkgPath = path.join(fromDir, 'package.json');
  if (!fs.existsSync(pkgPath)) return [];
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  return Object.keys(pkg.dependencies || {}).map((name) => ({ name, fromDir }));
}

// Walk production dependencies breadth-first, collecting unique packages.
// Both the backend (ROOT) and the bundled admin web app (ADMIN) ship in the
// release artifacts, so we seed the walk from both dependency roots.
function collect() {
  const seen = new Map(); // name@version -> info
  const queue = [...seedQueue(ROOT), ...seedQueue(ADMIN)];

  while (queue.length) {
    const { name, fromDir } = queue.shift();
    const dir = resolvePackageDir(name, fromDir);
    if (!dir) {
      console.warn(`WARN: could not resolve ${name} (from ${fromDir})`);
      continue;
    }
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const id = `${pkg.name}@${pkg.version}`;
    if (seen.has(id)) continue;
    seen.set(id, {
      name: pkg.name,
      version: pkg.version,
      license: normalizeLicense(pkg),
      author: authorOf(pkg),
      homepage: pkg.homepage || (pkg.repository && (pkg.repository.url || pkg.repository)) || null,
      licenseText: readLicenseText(dir),
    });
    for (const dep of Object.keys(pkg.dependencies || {})) {
      queue.push({ name: dep, fromDir: dir });
    }
  }

  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function render(pkgs) {
  const lines = [];
  lines.push('# Third-Party Notices');
  lines.push('');
  lines.push('Cachearoo is licensed under the MIT License (see [LICENSE](LICENSE)).');
  lines.push('');
  lines.push('When packaged for distribution (Windows installer / Debian package), Cachearoo');
  lines.push('bundles the third-party open-source components listed below. Each is the property');
  lines.push('of its respective copyright holders and is distributed under its own license. The');
  lines.push('full license texts are reproduced in the "License texts" section.');
  lines.push('');
  lines.push('> This file is generated by `node scripts/gen-third-party-notices.js`.');
  lines.push('> Do not edit by hand; regenerate after changing dependencies.');
  lines.push('');

  // Summary table
  lines.push('## Bundled components');
  lines.push('');
  lines.push('| Package | Version | License |');
  lines.push('| --- | --- | --- |');
  for (const p of pkgs) {
    lines.push(`| ${p.name} | ${p.version} | ${p.license} |`);
  }
  lines.push('');

  // Full license texts
  lines.push('## License texts');
  lines.push('');
  for (const p of pkgs) {
    lines.push(`### ${p.name}@${p.version}`);
    lines.push('');
    lines.push(`- License: ${p.license}`);
    if (p.author) lines.push(`- Author: ${p.author}`);
    if (p.homepage) lines.push(`- Homepage: ${String(p.homepage).replace(/^git\+/, '').replace(/\.git$/, '')}`);
    lines.push('');
    if (p.licenseText) {
      lines.push('```');
      lines.push(p.licenseText);
      lines.push('```');
    } else {
      lines.push(`_No license file shipped in the package. Declared license: ${p.license}._`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

const pkgs = collect();
fs.writeFileSync(OUT, render(pkgs));
console.log(`Wrote ${OUT} with ${pkgs.length} bundled packages.`);
